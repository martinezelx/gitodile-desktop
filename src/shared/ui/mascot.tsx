import React, { useId } from "react";

import { MASCOT_ARTWORK, type MascotNode } from "./mascotArtwork";

function renderNodes(nodes: readonly MascotNode[]): React.ReactNode[] {
  return nodes.map(([tag, props, children], index) =>
    React.createElement(tag, { key: index, ...props }, children ? renderNodes(children) : undefined),
  );
}

/**
 * How the mascot moves, for brand moments only (DESIGN.md § Motion):
 *
 * - `wink`: the front eye closes for a moment every few seconds, in step with
 *   the light that crosses the wordmark (About).
 * - `blink`: both eyes blink now and then, at an uneven pace and sometimes
 *   twice (the welcome screen).
 */
export type MascotMotion = "wink" | "blink";

export interface MascotProps {
  /**
   * Plays the welcome's one-time entrance: the outline draws itself, then the
   * colours fill in. Only the body carries the outline it traces.
   */
  entrance?: boolean;
  /** `body` shows the whole mascot; `head` its head, crest to snout tip. */
  variant?: "body" | "head";
  motion?: MascotMotion;
  className?: string;
}

/**
 * The GitOdile mascot, drawn inline from `mascotArtwork.ts` (generated by
 * `scripts/icons/mascot.mjs`) so its green body can follow the theme through
 * `--mascot-fill` (primitives.css). Its belly, toes and eyes are holes, so the
 * surface behind it shows through; the eyes are cut by a mask, one per mark,
 * so the front eye can close. Always decorative: the text beside it names the
 * screen or dialog.
 */
export function Mascot({ variant = "body", motion, entrance = false, className }: MascotProps) {
  const artwork = MASCOT_ARTWORK[variant];
  const maskId = `${useId()}-eyes`;
  const { x, y, width, height } = artwork.box;
  return (
    <svg
      className={["gitodile-mascot", `gitodile-mascot--${variant}`, motion && `gitodile-mascot--${motion}`, entrance && "gitodile-mascot--enter", className]
        .filter(Boolean)
        .join(" ")}
      viewBox={artwork.viewBox}
      aria-hidden="true"
      focusable="false"
    >
      <mask id={maskId} maskUnits="userSpaceOnUse" x={x} y={y} width={width} height={height}>
        <rect x={x} y={y} width={width} height={height} fill="#ffffff" />
        <g className="gitodile-mascot__eyes" fill="#000000">
          <path d={artwork.eyes[0]} />
          <path className="gitodile-mascot__wink" d={artwork.eyes[1]} />
        </g>
      </mask>
      <g mask={`url(#${maskId})`}>{renderNodes(artwork.nodes)}</g>
      {artwork.outline && renderNodes(artwork.outline)}
    </svg>
  );
}
